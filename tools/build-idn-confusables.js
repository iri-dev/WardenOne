/*
 * Generates the compact UTS #39 mapping embedded in domain-utils.js.
 *
 * WardenOne compares decoded IDN labels only with protected brand names made from ASCII
 * letters and digits. A confusable prototype containing any other character cannot equal
 * one of those names, so the generated runtime table keeps every official mapping whose
 * complete prototype is ASCII alphanumeric and omits irrelevant prototypes. The source
 * table is still parsed in full and the gate requires a plausible mapping count plus named
 * cross-script entries, so a format change cannot silently produce a tiny table.
 *
 *   node tools/build-idn-confusables.js
 *   node tools/build-idn-confusables.js --from confusables.txt
 *   node tools/build-idn-confusables.js --check
 */
'use strict';

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'domain-utils.js');
const SOURCE_URL = 'https://www.unicode.org/Public/security/latest/confusables.txt';
const BEGIN = '/* === BEGIN GENERATED UTS39 ASCII CONFUSABLES === */';
const END = '/* === END GENERATED UTS39 ASCII CONFUSABLES === */';
const MAX_AGE_DAYS = 400;
const MIN_SOURCE_MAPPINGS = 6500;
const MIN_ASCII_MAPPINGS = 1700;
const REQUIRED = new Map([
  [0x0131, 'i'], // Latin dotless i
  [0x0261, 'g'], // Latin script g
  [0x03c3, 'o'], // Greek sigma
  [0x0581, 'g'], // Armenian co
  [0x2ca3, 'p'], // Coptic ro
  [0xa4d0, 'b'], // Lisu ba
]);

const args = process.argv.slice(2);
const flag = (name) => args.includes(name);
const option = (name) => { const at = args.indexOf(name); return at >= 0 ? args[at + 1] : ''; };

function codePoints(raw) {
  return String(raw || '').trim().split(/\s+/).filter(Boolean).map((hex) => {
    if (!/^[0-9A-F]{4,6}$/i.test(hex)) throw new Error('invalid code point ' + JSON.stringify(hex));
    const value = Number.parseInt(hex, 16);
    if (value > 0x10ffff || (value >= 0xd800 && value <= 0xdfff)) throw new Error('invalid scalar value ' + hex);
    return value;
  });
}

function parseSource(text) {
  const rawSource = String(text || '');
  const source = rawSource.replace(/\r\n?/g, '\n');
  const version = (source.match(/^# Version:\s*([^\s]+)\s*$/m) || [])[1] || '';
  const dateText = (source.match(/^# Date:\s*(\d{4}-\d{2}-\d{2}),/m) || [])[1] || '';
  if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error('Unicode version header missing or malformed');
  if (!/^\d{4}-\d{2}-\d{2}$/.test(dateText)) throw new Error('Unicode date header missing or malformed');

  let sourceMappings = 0;
  const entries = new Map();
  for (const raw of source.split('\n')) {
    const line = raw.replace(/#.*/, '').trim();
    if (!line) continue;
    const fields = line.split(';').map((part) => part.trim());
    if (fields.length < 3 || fields[2] !== 'MA') throw new Error('unexpected confusables row: ' + raw);
    const from = codePoints(fields[0]);
    const to = codePoints(fields[1]);
    sourceMappings++;
    if (from.length !== 1) throw new Error('UTS #39 source is no longer one code point: ' + fields[0]);
    const target = String.fromCodePoint(...to);
    /* ASCII labels already go through the detector's established visual normaliser. Keeping
       only non-ASCII sources also leaves the generated skeleton directly comparable with the
       existing ASCII brand tables (UTS #39 maps ASCII m to "rn", for example). */
    if (from[0] <= 0x7f || !/^[A-Za-z0-9]+$/.test(target)) continue;
    entries.set(from[0], target.toLowerCase());
  }
  if (sourceMappings < MIN_SOURCE_MAPPINGS) throw new Error('only ' + sourceMappings + ' source mappings parsed');
  if (entries.size < MIN_ASCII_MAPPINGS) throw new Error('only ' + entries.size + ' ASCII-brand mappings parsed');
  for (const [cp, expected] of REQUIRED) {
    if (entries.get(cp) !== expected) throw new Error('required mapping U+' + cp.toString(16).toUpperCase() + ' -> ' + expected + ' is missing');
  }
  return {
    version,
    date: dateText,
    sha256: crypto.createHash('sha256').update(Buffer.from(rawSource, 'utf8')).digest('hex'),
    sourceMappings,
    entries: Array.from(entries).sort((a, b) => a[0] - b[0]),
  };
}

function render(data) {
  const packed = data.entries.map(([cp, target]) => cp.toString(16).toUpperCase() + '=' + target).join(' ');
  return [
    BEGIN,
    '/* Generated by tools/build-idn-confusables.js from Unicode UTS #39 confusables.txt.',
    ' * Only mappings with an ASCII-alphanumeric prototype can equal WardenOne\'s protected',
    ' * brand names. The packed table is expanded lazily, only when an IDN is inspected. */',
    "const WARDENONE_UTS39_VERSION = '" + data.version + "';",
    "const WARDENONE_UTS39_DATE = '" + data.date + "';",
    "const WARDENONE_UTS39_SHA256 = '" + data.sha256 + "';",
    "const WARDENONE_UTS39_SOURCE_MAPPINGS = " + data.sourceMappings + ';',
    "const WARDENONE_UTS39_ASCII_CONFUSABLES = '" + packed + "';",
    END,
  ].join('\n');
}

function replaceGenerated(text, block) {
  const start = text.indexOf(BEGIN);
  const end = text.indexOf(END, start);
  if (start < 0 || end < 0) throw new Error('generated UTS #39 markers are missing from domain-utils.js');
  return text.slice(0, start) + block + text.slice(end + END.length);
}

function parseShipped(text) {
  const version = (text.match(/^const WARDENONE_UTS39_VERSION = '([^']+)';$/m) || [])[1] || '';
  const date = (text.match(/^const WARDENONE_UTS39_DATE = '([^']+)';$/m) || [])[1] || '';
  const sha256 = (text.match(/^const WARDENONE_UTS39_SHA256 = '([^']+)';$/m) || [])[1] || '';
  const sourceMappings = Number((text.match(/^const WARDENONE_UTS39_SOURCE_MAPPINGS = (\d+);$/m) || [])[1] || 0);
  const packed = (text.match(/^const WARDENONE_UTS39_ASCII_CONFUSABLES = '([^']*)';$/m) || [])[1] || '';
  const entries = [];
  for (const record of packed.split(' ').filter(Boolean)) {
    const match = /^([0-9A-F]{2,6})=([a-z0-9]{1,4})$/.exec(record);
    if (!match) throw new Error('malformed packed mapping ' + JSON.stringify(record));
    const cp = Number.parseInt(match[1], 16);
    if (cp > 0x10ffff || (cp >= 0xd800 && cp <= 0xdfff)) throw new Error('invalid packed scalar U+' + match[1]);
    entries.push([cp, match[2]]);
  }
  return { version, date, sha256, sourceMappings, entries };
}

function check() {
  const text = fs.readFileSync(OUT, 'utf8');
  const problems = [];
  let data;
  try { data = parseShipped(text); } catch (error) { problems.push(error.message); data = { entries: [] }; }
  if (!/^\d+\.\d+\.\d+$/.test(data.version || '')) problems.push('version stamp is malformed');
  if (!/^\d{4}-\d{2}-\d{2}$/.test(data.date || '')) problems.push('date stamp is malformed');
  if (!/^[a-f0-9]{64}$/.test(data.sha256 || '')) problems.push('source SHA-256 is malformed');
  if (!(data.sourceMappings >= MIN_SOURCE_MAPPINGS)) problems.push('source mapping count is too small');
  if (!(data.entries.length >= MIN_ASCII_MAPPINGS)) problems.push('ASCII mapping count is too small');
  const age = (Date.now() - Date.parse((data.date || '') + 'T00:00:00Z')) / 86400000;
  if (!(age >= 0 && age < MAX_AGE_DAYS)) problems.push('Unicode data is ' + Math.round(age) + ' days old (limit ' + MAX_AGE_DAYS + ')');
  const sorted = data.entries.slice().sort((a, b) => a[0] - b[0]);
  if (sorted.some((entry, index) => entry[0] !== data.entries[index][0])) problems.push('mappings are not sorted');
  if (new Set(data.entries.map((entry) => entry[0])).size !== data.entries.length) problems.push('duplicate mappings');
  const values = new Map(data.entries);
  for (const [cp, expected] of REQUIRED) if (values.get(cp) !== expected) problems.push('required mapping U+' + cp.toString(16).toUpperCase() + ' is missing');
  if (!problems.length) {
    const block = text.slice(text.indexOf(BEGIN), text.indexOf(END) + END.length);
    if (block !== render(data)) problems.push('generated block differs from the canonical rendering');
  }
  if (problems.length) {
    for (const problem of problems) console.error('domain-utils.js UTS #39 data: ' + problem);
    process.exit(1);
  }
  console.log('UTS #39 ASCII-brand map ok: ' + data.entries.length + ' mappings, Unicode ' + data.version + ', ' + Math.round(age) + ' days old');
}

async function sourceText() {
  const from = option('--from');
  if (from) return fs.readFileSync(path.resolve(from), 'utf8');
  const response = await fetch(SOURCE_URL, { headers: { 'user-agent': 'WardenOne build (tools/build-idn-confusables.js)' } });
  if (!response.ok) throw new Error('Unicode fetch failed: HTTP ' + response.status);
  return response.text();
}

async function main() {
  if (flag('--check')) return check();
  const data = parseSource(await sourceText());
  const current = fs.readFileSync(OUT, 'utf8');
  const next = replaceGenerated(current, render(data));
  fs.writeFileSync(OUT, next, 'utf8');
  console.log('wrote ' + data.entries.length + ' Unicode ' + data.version + ' ASCII-brand mappings to domain-utils.js');
}

main().catch((error) => {
  console.error(error && error.stack ? error.stack : error);
  process.exit(1);
});
