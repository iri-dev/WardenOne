function domainApi(rules) {
  const sandbox = Object.assign({}, BASE);
  vm.createContext(sandbox);
  const data = rules === undefined ? PSL : (rules === null ? '' : "const WARDENONE_PSL_PRIVATE_RULES = " + JSON.stringify(rules.join('\n')) + ';');
  vm.runInContext(DOMAIN + '\n' + data + '\nthis.api={regDomain,registrableDomain,sameSiteDomain,hostMatchesSite,'
    + 'siteIdentity:typeof siteIdentity==="function"?siteIdentity:null,'
    + 'sameSiteIdentity:typeof sameSiteIdentity==="function"?sameSiteIdentity:null,'
    + 'pslIndex:typeof wardenOnePslIndex==="function"?wardenOnePslIndex:null};', sandbox);
  return sandbox.api;
}

section('shared helper', () => {
  check('psl-private.js is generated and present', PSL.length > 0 && /GENERATED by tools\/build-psl\.js/.test(PSL));
  check('the generated file carries the list version it was built from', /^const WARDENONE_PSL_VERSION = '\d{4}-\d{2}-\d{2}_\d{2}-\d{2}-\d{2}_UTC';$/m.test(PSL));
  const on = domainApi();
  check('siteIdentity exists', typeof on.siteIdentity === 'function');
  check('sameSiteIdentity exists', typeof on.sameSiteIdentity === 'function');
  if (!on.siteIdentity || !on.sameSiteIdentity) return;

  check('a Webflow tenant is its own site', on.siteIdentity(VICTIM) === VICTIM, on.siteIdentity(VICTIM));
  check('www. and deeper labels fold into the tenant', on.siteIdentity('www.' + VICTIM) === VICTIM && on.siteIdentity('cdn.assets.' + VICTIM) === VICTIM);
  check('the platform apex stays itself', on.siteIdentity('webflow.io') === 'webflow.io');
  check('two Webflow tenants are not one site', on.sameSiteIdentity(VICTIM, ATTACKER) === false);
  check('a tenant and its own subdomain are one site', on.sameSiteIdentity(VICTIM, 'cdn.' + VICTIM) === true);
  check('the curated table still answers the same', on.siteIdentity('docs.alice.github.io') === 'alice.github.io' && on.sameSiteIdentity('alice.github.io', 'bob.github.io') === false);
  check('ordinary sites are unchanged', on.siteIdentity('accounts.example.com') === 'example.com' && on.siteIdentity('portal.example.co.uk') === 'example.co.uk');
  check('siblings of an ordinary site stay one site', on.sameSiteIdentity('accounts.example.com', 'api.example.com') === true);
  check('IP literals and localhost are themselves', on.siteIdentity('10.0.0.1') === '10.0.0.1' && on.siteIdentity('localhost') === 'localhost');
  check('a wildcard rule takes one label as the platform', on.siteIdentity('app.tenant.compute.amazonaws.com') === 'app.tenant.compute.amazonaws.com'
    && on.sameSiteIdentity('a.eu-west-1.compute.amazonaws.com', 'b.eu-west-1.compute.amazonaws.com') === false);
  check('IDN rules match the punycode the URL parser produces', on.siteIdentity('shop.xn--gnstigbestellen-zvb.de') === 'shop.xn--gnstigbestellen-zvb.de');

  /* The list's own algorithm on synthetic rules: an exception beats a wildcard and names the
     suffix minus its first label; a wildcard stands for exactly one label. */
  const synthetic = domainApi(['*.kawasaki.example', '!city.kawasaki.example', 'newplatform.example']);
  check('wildcard: the label it stands for is itself a suffix, and a tenant under that is its own site',
    synthetic.siteIdentity('www.foo.kawasaki.example') === 'foo.kawasaki.example' && synthetic.siteIdentity('app.foo.kawasaki.example') === 'app.foo.kawasaki.example'
    && synthetic.sameSiteIdentity('app.foo.kawasaki.example', 'other.foo.kawasaki.example') === false);
  check('exception: the excepted name is an ordinary site again', synthetic.siteIdentity('www.city.kawasaki.example') === 'city.kawasaki.example');
  check('a newly added suffix separates its tenants at once', synthetic.sameSiteIdentity('one.newplatform.example', 'two.newplatform.example') === false);
  /* And the mutation the card asks for: take a rule away and its tenants collapse again, which
     is what proves the data is deciding and not a coincidence of the curated table. */
  const without = domainApi(PSL ? PSL.match(/^  '([^']+)',$/gm).map((l) => l.slice(3, -2)).filter((r) => r !== 'webflow.io') : []);
  check('remove webflow.io from the data and the pair collapses (the data decides)', without.sameSiteIdentity(VICTIM, ATTACKER) === true);

  /* Every private rule, swept: the tenant is a suffix of its host, the identity is never shorter
     than the curated answer, siblings differ and a subdomain folds in. */
  const index = on.pslIndex();
  check('the index loaded from the generated file', !!(index && index.loaded && index.plain.size > 3000 && index.wildcard.size > 100), index && index.plain.size);
  let swept = 0;
  const violations = [];
  for (const rule of Array.from(index.plain).concat(Array.from(index.wildcard).map((w) => 'label.' + w))) {
    const a = 'alice.' + rule;
    const b = 'bob.' + rule;
    const site = on.siteIdentity(a);
    const loose = on.registrableDomain(a);
    swept++;
    if (!(a === site || a.endsWith('.' + site)) || site.length < loose.length || on.sameSiteIdentity(a, b) || !on.sameSiteIdentity(a, 'www.' + a)) {
      if (violations.length < 5) violations.push(rule + ' -> ' + site);
    }
  }
  check('every private rule separates its tenants and never widens the curated answer (' + swept + ' rules)', swept > 3000 && !violations.length, violations.join(', '));

  /* No rules loaded (every frame, every page): the answer is registrableDomain's, exactly. */
  const off = domainApi(null);
  const hosts = [VICTIM, ATTACKER, 'www.' + VICTIM, 'docs.alice.github.io', 'accounts.example.com', 'portal.example.co.uk', 'x.foo.compute.amazonaws.com', '10.0.0.1', 'webflow.io'];
  check('without the rules siteIdentity is registrableDomain', hosts.every((h) => off.siteIdentity(h) === off.registrableDomain(h)));
  check('without the rules the pair still collapses -- the floor, not a second table', off.sameSiteIdentity(VICTIM, ATTACKER) === true);
});

