/*
 * Two tenants of one platform are never one site (SEC-07).
 * Run: node tools/test-tenant-isolation.js
 *
 * domain-utils.js decided "same owner" from a hand-written table of 26 shared-hosting suffixes and a
 * two-label fallback, so on any platform the table did not name -- webflow.io was the audited
 * case -- victim.webflow.io and attacker.webflow.io collapsed to webflow.io. That verdict sat at
 * the credential boundary: sameParty() said "same site", credentialFrameTarget() returned null, and
 * the token, card and skimmer blockers never looked at the request. The forced-navigation
 * interstitials, the redirect-warning cross-site test, the logger's party column, the script-drift
 * and smart-script party checks, the cookie audit and the Forget-Me wipe scope all asked the same
 * question and got the same wrong answer.
 *
 * The private half of the Public Suffix List is generated into psl-private.js now (tools/build-psl.js)
 * and read by siteIdentity(), which is never broader than registrableDomain(); the worker imports it
 * and tells each frame its own site with the content config, and sameParty() in the frame refuses to
 * call a host inside that site the same party as one outside it. Everything below is lifted from the
 * shipped sources and driven with the tenant pair from the card; the list is swept rule by rule; and
 * the two properties that make the change safe -- no rules loaded means no change, and a site sent to
 * a frame can withdraw trust but never grant it -- are checked as properties, not examples.
 */
