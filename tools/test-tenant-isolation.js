function guardRealm(frameSite, baseUrl) {
  const sandbox = Object.assign({}, BASE, {
    guardConfig: Object.assign({ __configReady: !!frameSite, enabled: true }, frameSite ? { frameSite } : {}),
    location: { hostname: '', href: baseUrl || '' },
    document: { baseURI: baseUrl || '', referrer: '' },
  });
  vm.createContext(sandbox);
  const parts = [DOMAIN];
  for (const name of ['regHost', 'baseDomain', 'ownSite', 'sameParty', 'credentialFrameSourceHost', 'credentialFrameTarget']) {
    try { parts.push(grabFn(GUARD, name)); } catch (e) { parts.push('/* ' + name + ' missing */'); }
  }
  parts.push('function cfg() { return guardConfig; }');
  parts.push('function credentialFrameBaseUrl() { return document.baseURI; }');
  parts.push('this.api = { sameParty, credentialFrameTarget };');
  vm.runInContext(parts.join('\n'), sandbox, { filename: 'guard-lift.js' });
  return sandbox.api;
}

