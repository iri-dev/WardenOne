'use strict';

/* Generate search-loggers.js from whole-domain block rules in rules.json, excluding allows/path rules.
   Register before search-junk.js so result warnings need no delayed worker lookup.
   Run: node tools/build-search-loggers.js [--check] */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const RULES = path.join(ROOT, 'rules.json');
const OUT = path.join(ROOT, 'search-loggers.js');

function packagedLoggerDomains(rules) {
  const out = new Set();
  for (const rule of (Array.isArray(rules) ? rules : [])) {
    const cond = rule && rule.condition;
    if (!rule || !rule.action || rule.action.type !== 'block' || !cond) continue;
    if (cond.urlFilter || cond.regexFilter) continue;
    if (!Array.isArray(cond.resourceTypes) || !cond.resourceTypes.includes('main_frame')) continue;
    for (const d of (Array.isArray(cond.requestDomains) ? cond.requestDomains : [])) {
      const v = String(d || '').trim().toLowerCase();
      if (/^[a-z0-9.-]+\.[a-z]{2,}$/.test(v) && !v.includes('..')) out.add(v);
    }
  }
  return out;
}

function render(list) {
  return [
    '/* WardenOne — Copyright (C) 2026 iri',
    '   Licensed under the GNU General Public License v3 or later. See LICENSE.',
    '   Official source: https://github.com/iri-dev/WardenOne',
    '   Upstream filter-list attribution: CREDITS.md',
    '   Redistributing a modified copy? GPLv3 section 5(a) requires you to mark it as changed,',
    '   with the date, and to keep these notices intact. */',
    '/* GENERATED by tools/build-search-loggers.js from rules.json -- do not edit by hand.',
    '   The domains the packaged IP-logger ruleset blocks outright, for the search-results',
    '   page (search-junk.js), which is registered right after this file and reads the list',
    '   from here: a logger in the results is named the moment it is on the page, with no',
    '   storage read and no round trip to a worker that may be asleep. This file is only',
    '   registered while the warning pass is on -- its being here is the switch. */',
    'var WO_SEARCH_LOGGERS = [',
    ...list.map((d) => "  '" + d + "',"),
    '];',
    '',
  ].join('\n');
}

function currentText() {
  const rules = JSON.parse(fs.readFileSync(RULES, 'utf8'));
  return render(Array.from(packagedLoggerDomains(rules)).sort());
}

if (require.main === module) {
  const text = currentText();
  const count = (text.match(/^  '/gm) || []).length;
  if (process.argv.includes('--check')) {
    const shipped = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (shipped !== text) {
      console.error('[fail] search-loggers.js is stale against rules.json -- run: node tools/build-search-loggers.js');
      process.exit(1);
    }
    console.log('[ok] search-loggers.js is current (' + count + ' domains)');
  } else {
    fs.writeFileSync(OUT, text);
    console.log('search-loggers.js written (' + count + ' domains)');
  }
}

module.exports = { packagedLoggerDomains, render, currentText };
