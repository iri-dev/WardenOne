'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const crypto = require('crypto');
const { helpers } = require('./build-cname-data.js');
const ROOT = path.resolve(__dirname, '..');
function build() {
  const { WOCname, siteIdentity } = helpers();
  const cname = JSON.parse(fs.readFileSync(path.join(ROOT, 'cname-trackers.json')));
  const mapping = WOCname.validateData(cname);
  const trackers = fs.readFileSync(path.join(ROOT, 'rules-trackers.json'));
  const trackerRules = JSON.parse(trackers).filter(rule => rule.action?.type === 'block' && rule.condition?.requestDomains).map(rule => {
    if (Object.keys(rule.condition).some(key => !['requestDomains', 'resourceTypes', 'initiatorDomains'].includes(key))) throw new Error('Tracker observation condition needs review');
    const hosts = rule.condition.requestDomains.map(host => WOCname.normalizeHost(host));
    const initiators = (rule.condition.initiatorDomains || []).map(host => WOCname.normalizeHost(host));
    if (!hosts.length || hosts.concat(initiators).some(host => !host) || !Array.isArray(rule.condition.resourceTypes)) throw new Error('Invalid tracker observation rule');
    return { hosts, types: rule.condition.resourceTypes, ...(initiators.length ? { initiators } : {}) };
  });
  const trackerHosts = [...new Set(trackerRules.flatMap(rule => rule.hosts))].sort();
  if (trackerHosts.some(host => !host) || trackerHosts.length > 1000) throw new Error('Invalid tracker observation scope');
  const background = fs.readFileSync(path.join(ROOT, 'background.js'), 'utf8');
  const literal = background.match(/const FINGERPRINT_LIBRARY_DOMAIN_FILTERS = (\[[\s\S]*?\]);/);
  if (!literal) throw new Error('Missing fingerprint library inventory');
  const fingerprintHosts = [...vm.runInNewContext(literal[1])].map(host => WOCname.normalizeHost(host)).sort();
  if (fingerprintHosts.some(host => !host) || fingerprintHosts.length > 80) throw new Error('Invalid fingerprint observation scope');
  const cnameHosts = [...mapping.keys()].filter(host => WOCname.resolve(mapping, host, cname.source));
  return { schema: 1, cnameRevision: cname.revision,
    trackerSha256: crypto.createHash('sha256').update(trackers).digest('hex'),
    cnameHosts, canonicalSites: [...new Set(cnameHosts.map(host => siteIdentity(mapping.get(host))))].sort(), trackerHosts, trackerRules, fingerprintHosts };
}
function main(mode) {
  if (!['--check', '--build'].includes(mode)) throw new Error('Use --check or --build');
  const output = '/* WardenOne — GPL-3.0-or-later. Generated by tools/build-tracker-network-data.js.\n'
    + '   CNAME data: Copyright 2021 Adguard Software Ltd, MIT; see licenses/AdGuard-CNAME-MIT.txt.\n'
    + '   Tracker data attribution: CREDITS.md and THIRD_PARTY_NOTICES.html. */\n'
    + "'use strict';\nconst WO_TRACKER_NETWORK_DATA = Object.freeze(" + JSON.stringify(build()) + ');\n';
  const target = path.join(ROOT, 'tracker-network-data.js');
  if (mode === '--build') fs.writeFileSync(target, output);
  else if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Tracker network scope differs from its reviewed inputs');
  console.log('[ok] tracker network observation scope matches local curated inputs');
}
module.exports = { build };
if (require.main === module) main(process.argv[2]);
