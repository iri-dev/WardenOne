/* What a file would add to what is here. Nothing already present is touched. */
function listsPlan(file, have) {
  const lower = (list) => new Set(list.map((s) => s.toLowerCase()));
  const blocked = lower(have.blockedSites), scripts = lower(have.trustedScriptSites), downloads = lower(have.trustedDownloadSites);
  const ownLines = new Set(ruleLines(have.myFilters));
  const subscribed = new Set(have.filterLists.map((l) => l.url));
  return {
    blockedSites: file.blockedSites.filter((p) => !blocked.has(p.toLowerCase())),
    trustedScriptSites: file.trustedScriptSites.filter((h) => !scripts.has(h.toLowerCase())),
    trustedDownloadSites: file.trustedDownloadSites.filter((h) => !downloads.has(h.toLowerCase())),
    firewall: cellsOf(file.firewall).filter(([site, domain, column, verdict]) => ((have.firewall[site] || {})[domain] || {})[column] !== verdict),
    hidden: pairsOf(file.hiddenElements).filter(([host, selector]) => !(have.hiddenElements[host] || []).includes(selector)),
    filterLines: ruleLines(file.myFilters).filter((line, i, all) => !ownLines.has(line) && all.indexOf(line) === i),
    filterLists: file.filterLists.filter((l) => !subscribed.has(l.url)),
    mode: file.scriptShieldMode !== have.scriptShieldMode ? file.scriptShieldMode : ''
  };
}
function planWords(plan) {
  return [[plan.blockedSites.length, 'blocked site'], [plan.trustedScriptSites.length, 'trusted script site'], [plan.trustedDownloadSites.length, 'trusted download site'],
    [plan.firewall.length, 'firewall decision'], [plan.hidden.length, 'hidden element'], [plan.filterLines.length, 'filter rule'], [plan.filterLists.length, 'subscribed list']]
    .filter(([n]) => n).map(([n, word]) => plural(n, word));
}
async function applyListsPlan(plan, have) {
  const added = { blockedSites: 0, trustedScriptSites: 0, trustedDownloadSites: 0, firewall: 0, hidden: 0, filterLines: 0, filterLists: 0 };
  const failed = [];
  const notes = [];
  const why = (res) => trimStop(res.error || 'WardenOne did not answer');
  for (const pattern of plan.blockedSites) {
    const res = await ask({ kind: 'blocklist-add', pattern, scope: 'forever' });
    if (res.ok) added.blockedSites++; else if (!/already/i.test(res.error || '')) failed.push(pattern + ': ' + why(res));
  }
  for (const host of plan.trustedScriptSites) {
    const res = await ask({ kind: 'script-trust-add', host });
    if (res.ok) added.trustedScriptSites++; else failed.push(host + ': ' + why(res));
  }
  for (const host of plan.trustedDownloadSites) {
    const res = await ask({ kind: 'download-trust-add', host });
    if (res.ok) added.trustedDownloadSites++; else failed.push(host + ': ' + why(res));
  }
  for (const [site, domain, column, verdict] of plan.firewall) {
    const res = await ask({ kind: 'firewall-set', site, domain, column, verdict });
    if (res.ok) added.firewall++; else failed.push('Firewall ' + site + ' › ' + domain + ': ' + why(res));
  }
  for (const [hostname, selector] of plan.hidden) {
    const res = await ask({ kind: 'hidden-add', hostname, selector });
    if (res.ok) added.hidden++; else failed.push('Hidden element on ' + hostname + ': ' + why(res));
  }
  if (plan.filterLines.length) {
    const text = String(have.myFilters || '').replace(/\s*$/, '');
    const res = await ask({ kind: 'user-rules-set', text: (text ? text + '\n' : '') + plan.filterLines.join('\n') });
    if (res.ok) added.filterLines = plan.filterLines.length; else failed.push('Your rules: ' + why(res));
  }
  for (const list of plan.filterLists) {
    const res = await ask({ kind: 'custom-list-add', url: list.url });
    if (!res.ok) { failed.push(list.url + ': ' + why(res)); continue; }
    added.filterLists++;
    const row = (res.lists || []).find((l) => l.url === list.url);
    if (!list.enabled && row) await ask({ kind: 'custom-list-toggle', id: row.id, enabled: false });
  }
  /* Lockdown blocks every script except on sites you allowed one by one, and those can't travel
     in a file, so turning it on here would break every site at once. It is left for you. */
  if (plan.mode === 'lockdown') notes.push('Script Shield’s Lockdown wasn’t turned on, because the sites you allowed under it can’t be carried in a file. Turn it on under Security when you’re ready.');
  else if (plan.mode) {
    const res = await ask({ kind: 'set-script-shield-mode', mode: plan.mode });
    if (res.ok) { adoptConfig(config, plan.mode); notes.push('Script Shield is now ' + (plan.mode === 'smart' ? 'Smart' : 'off') + '.'); } else failed.push('Script Shield: ' + why(res));
  }
  return { added, failed, notes };
}

