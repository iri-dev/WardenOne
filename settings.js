/* One form for a word and its plural: "entries" is "entry", but "cookies" is "cookie". */
function searchNorm(word) {
  let w = String(word || '').toLowerCase().replace(/[’'`]/g, '').replace(/[^a-z0-9]/g, '');
  if (w.length > 4 && w.endsWith('ies') && !/(?:cook|mov)ies$/.test(w)) w = w.slice(0, -3) + 'y';
  else if (w.length >= 3 && w.endsWith('s') && !/(?:ss|us|is)$/.test(w)) w = w.slice(0, -1);
  return w;
}
/* "Third-party" is found by "third party", "thirdparty" and "party": the joined word and its parts. */
function searchTokens(text) {
  const out = new Set();
  String(text || '').toLowerCase().split(/[^a-z0-9’'\-–]+/).forEach((chunk) => {
    const parts = chunk.split(/[-–]+/).map(searchNorm).filter(Boolean);
    parts.forEach((p) => out.add(p));
    if (parts.length > 1) out.add(searchNorm(chunk.replace(/[-–’']/g, '')));
  });
  return out;
}
/* Optimal string alignment distance, which counts two swapped letters as one slip, and gives
   up as soon as it is past `max`. */
function searchDistance(a, b, max) {
  if (Math.abs(a.length - b.length) > max) return max + 1;
  let prev2 = null, prev = Array.from({ length: b.length + 1 }, (_, j) => j);
  for (let i = 1; i <= a.length; i++) {
    const row = [i];
    let best = i;
    for (let j = 1; j <= b.length; j++) {
      const cost = a[i - 1] === b[j - 1] ? 0 : 1;
      let v = Math.min(prev[j] + 1, row[j - 1] + 1, prev[j - 1] + cost);
      if (prev2 && i > 1 && j > 1 && a[i - 1] === b[j - 2] && a[i - 2] === b[j - 1]) v = Math.min(v, prev2[j - 2] + 1);
      row.push(v);
      if (v < best) best = v;
    }
    if (best > max) return max + 1;
    prev2 = prev;
    prev = row;
  }
  return prev[b.length];
}
const SEARCH_SYNONYMS = new Map();
SEARCH_GROUPS.forEach((group) => {
  const words = group.map(searchNorm);
  words.forEach((w) => { if (!SEARCH_SYNONYMS.has(w)) SEARCH_SYNONYMS.set(w, new Set()); words.forEach((o) => { if (o !== w) SEARCH_SYNONYMS.get(w).add(o); }); });
});
/* How one word of the query matches one token: 1 the word itself, then a word it starts, an
   everyday word for it, a word starting with that, and last a near miss. 0 is no match. */
function searchStrength(token, q) {
  if (token === q.word) return 1;
  if (q.word.length >= 3 && token.startsWith(q.word)) return 0.8;
  if (q.alts.has(token)) return 0.65;
  for (const alt of q.alts) if (alt.length >= 3 && token.startsWith(alt)) return 0.55;
  return q.fuzzy.has(token) ? 0.5 : 0;
}
/* The query worked out once against every word the settings use: what each typed word may match,
   and which typed words were read as something else because they matched nothing as typed. */
/* The words of a query, in order. A typed hyphen keeps the joined word ("pop-ups" is "popup"), and
   two words that only mean something together are joined ("pop ups", "sign in"). */
function searchQueryWords(query, vocab) {
  const words = String(query || '').toLowerCase().split(/[^a-z0-9’'\-–]+/).map((chunk) => searchNorm(chunk.replace(/[-–’']/g, ''))).filter(Boolean);
  const known = (w) => vocab.has(w) || (w.length >= 4 && Array.from(vocab).some((t) => t.startsWith(w)));
  const out = [];
  for (let i = 0; i < words.length; i++) {
    const joined = i + 1 < words.length ? searchNorm(words[i] + words[i + 1]) : '';
    if (joined && known(joined) && !(known(words[i]) && known(words[i + 1]) && !vocab.has(joined))) { out.push(joined); i++; } else out.push(words[i]);
  }
  return out;
}
function searchPlan(query, vocab) {
  const typed = searchQueryWords(query, vocab);
  const meaningful = typed.filter((w) => !SEARCH_STOP.has(w));
  const words = (meaningful.length ? meaningful : typed).map((word) => ({ word, alts: SEARCH_SYNONYMS.get(word) || new Set(), fuzzy: new Set() }));
  const corrected = [];
  words.forEach((q) => {
    const direct = Array.from(vocab).some((t) => searchStrength(t, q) > 0);
    /* Short words have too many neighbours one letter away to guess at ("dark" is not "mark"). */
    if (direct || q.word.length < 5) return;
    const max = q.word.length >= 8 ? 2 : 1;
    let best = '', bestDistance = max + 1;
    vocab.forEach((t) => {
      if (t.length < 5) return;
      const d = searchDistance(q.word, t, max);
      if (d <= max) { q.fuzzy.add(t); if (d < bestDistance) { best = t; bestDistance = d; } }
    });
    if (best) corrected.push([q.word, best]);
  });
  return { words, corrected };
}
/* A score for one item from its fields (each a token set and a weight), or 0 when a word of the
   query matches nothing in it. With `any`, an item counts if some word matches. */
function searchScore(fields, plan, any) {
  let total = 0;
  for (const q of plan.words) {
    let best = 0;
    for (const field of fields) {
      let strength = 0;
      for (const token of field.tokens) {
        const s = searchStrength(token, q);
        if (s > strength) strength = s;
        if (strength === 1) break;
      }
      best = Math.max(best, strength * field.weight);
    }
    if (!best && !any) return 0;
    total += best;
  }
  return total;
}
