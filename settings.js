function readSwitch(key) {
  if (key === 'js-global') return scriptMode === 'lockdown';
  if (key === 'js-smart') return scriptMode === 'smart';
  if (key === 'forget-enable') return config.forgetMeMode === 'all' && Number(config.forgetMeAllConfirmedAt || 0) > 0;
  /* The engine also honours the legacy alias, so the switch shows what actually runs. */
  if (key === 'antiFingerprintNoise' && config.antiFingerprint === true) return true;
  const value = config[FIELD_OF[key] || key];
  return typeof value === 'boolean' ? value : !!DEFAULT_OF[key];
}
