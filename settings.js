const countOf = (value) => Number.isFinite(Number(value)) ? Math.max(0, Math.floor(Number(value))) : 0;
async function loadPreview() {
  if (typeof chrome === 'undefined' || !chrome.tabs?.query) return;
  const number = ++previewLoadNumber;
  try {
    const [tabs, currentTab] = await Promise.all([chrome.tabs.query({}), chrome.tabs.getCurrent()]);
    if (number !== previewLoadNumber) return;
    const websites = tabs.filter((tab) => /^https?:\/\//i.test(String(tab.url || '')) && Number.isInteger(tab.id));
    const sameWindow = currentTab && websites.filter((tab) => tab.windowId === currentTab.windowId);
    const candidates = sameWindow && sameWindow.length ? sameWindow : websites;
    candidates.sort((a, b) => (Number(b.lastAccessed) || 0) - (Number(a.lastAccessed) || 0));
    const tab = candidates[0];
    if (!tab) previewState = { status: 'empty' };
    else {
      const report = await backgroundCall({ kind: 'site-dashboard', tabId: tab.id });
      if (number !== previewLoadNumber) return;
      if (!report.web || !report.host) previewState = { status: 'empty' };
      else {
        const net = report.network || {};
        const counted = wardenSiteDashSummarize(report);
        const trackers = countOf(counted.cats.trackers), ads = countOf(counted.cats.ads);
        previewState = { status: 'ready', host: report.host, tabId: tab.id,
          activity: { networkAvailable: !!net.available, trackers, ads,
            other: Math.max(0, countOf(counted.total) - trackers - ads) } };
      }
    }
  } catch (_) {
    if (number !== previewLoadNumber) return;
    previewState = { status: 'error' };
  }
  /* The health check asks about the website found here, so it follows it. */
  if (number === previewLoadNumber) { renderRail(); scheduleHealth(); }
}

