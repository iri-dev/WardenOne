async function siteAction(button) {
  const { siteSource: source, siteId: id, siteAction: verb } = button.dataset;
  const all = Object.keys(siteState).filter((k) => Array.isArray(siteState[k])).flatMap((k) => siteState[k]);
  const row = all.find((entry) => entry.source === source && entry.id === id);
  if (!row) return;
  if (verb === 'edit' && source === 'firewall') {
    chrome.tabs.create({ url: chrome.runtime.getURL('firewall.html') + '?site=' + encodeURIComponent(id) });
    return;
  }
  if (source === 'hidden' && !confirm('Bring back everything you hid on ' + id + '?\n\nIt shows again the next time its pages load.')) return;
  try {
    if (source === 'blocked') await backgroundCall({ kind: 'blocklist-remove', id });
    else if (source === 'trusted') await backgroundCall({ kind: 'script-trust-remove', host: id });
    else if (source === 'downloads') await backgroundCall({ kind: 'download-trust-remove', host: id });
    else if (source === 'hidden') await backgroundCall({ kind: 'hidden-clear', hostname: id });
    else if (source === 'paused') {
      await writeConfig((before) => {
        const until = Object.assign({}, isObj(before.allowlistUntil) ? before.allowlistUntil : {});
        delete until[id];
        return { allowlist: (Array.isArray(before.allowlist) ? before.allowlist : []).filter((host) => host !== id), allowlistUntil: until };
      });
    } else if (source === 'override') {
      const [host, key] = id.split('|');
      await writeConfig((before) => {
        const map = JSON.parse(JSON.stringify(isObj(before.siteOverrides) ? before.siteOverrides : {}));
        if (isObj(map[host])) { delete map[host][key]; if (!Object.keys(map[host]).length) delete map[host]; }
        return { siteOverrides: map };
      });
    } else if (source === 'neversleep') {
      await writeConfig((before) => ({ memoryNeverSleepHosts: (Array.isArray(before.memoryNeverSleepHosts) ? before.memoryNeverSleepHosts : []).filter((host) => host !== id) }));
    } else if (source === 'webglblock' || source === 'webglallow') {
      const field = source === 'webglblock' ? 'webglSaverBlockHosts' : 'webglSaverAllowHosts';
      await writeConfig((before) => ({ [field]: (Array.isArray(before[field]) ? before[field] : []).filter((host) => host !== id) }));
    }
    await loadSites();
  } catch (error) { toast('Could not change ' + row.host + ': ' + error.message); }
}
