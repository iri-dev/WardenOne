const stable = (v) => (Array.isArray(v) ? '[' + v.map(stable).join(',') + ']'
  : isObj(v) ? '{' + Object.keys(v).sort().map((k) => JSON.stringify(k) + ':' + stable(v[k])).join(',') + '}' : JSON.stringify(v === undefined ? null : v));
const sameValue = (a, b) => stable(a) === stable(b);
const bullets = (items) => items.slice(0, 10).map((item) => '• ' + item).join('\n') + (items.length > 10 ? '\n…and ' + (items.length - 10) + ' more' : '');
async function importSettings(file) {
  if (!file) return;
  if (!loaded) { setResult('backup', 'Still reading your settings. Try again in a moment.', 'err'); return; }
  if (file.size > SETTINGS_FILE_MAX_BYTES) { setResult('backup', 'That file is too large to be a settings export.', 'err'); return; }
  let parsed = null;
  try { parsed = JSON.parse(await file.text()); } catch (_) { setResult('backup', 'That file is not valid JSON.', 'err'); return; }
  if (!parsed || typeof parsed !== 'object' || parsed.format !== SETTINGS_FILE_MARKER || !isObj(parsed.settings)) {
    setResult('backup', 'That does not look like a WardenOne settings file.', 'err');
    return;
  }
  const result = sanitizeImportedSettings(parsed.settings);
  let held = false;
  /* History clearing needs the browser's permission, and a file can't grant it. */
  if (result.settings.forgetMeHistory === true) {
    let granted = false;
    try { granted = await chrome.permissions.contains({ permissions: ['history'] }); } catch (_) {}
    if (!granted) { result.settings.forgetMeHistory = false; held = true; }
  }
  setResult('backup', 'Reading ' + file.name + '…', '');
  let have = null;
  let plan = null;
  if (isObj(parsed.lists)) {
    try { have = await collectLists(); } catch (error) { setResult('backup', 'Nothing was changed: ' + error.message + '.', 'err'); return; }
    plan = listsPlan(cleanLists(parsed.lists), have);
  }
  const stored = await localRead(CONFIG_KEY);
  const current = Object.assign({}, POPUP_DEFAULTS, isObj(stored[CONFIG_KEY]) ? stored[CONFIG_KEY] : {});
  const changing = Object.keys(result.settings).filter((key) => !sameValue(current[key], result.settings[key]));
  const adding = plan ? planWords(plan) : [];
  const levelChange = plan && plan.mode ? 'Script Shield ' + (plan.mode === 'lockdown' ? 'Lockdown (left for you to turn on)' : plan.mode === 'smart' ? 'Smart' : 'off') : '';
  if (!changing.length && !adding.length && !levelChange) {
    setResult('backup', 'Everything in ' + file.name + ' is already here. Nothing was changed.', 'ok');
    return;
  }
  const named = changing.map((key) => ROW_OF_FIELD[key] || key).filter((key) => pageOfKey[key]).map((key) => info(key).name);
  const ignored = result.ignored ? ' ' + plural(result.ignored, 'unrecognised entry', 'unrecognised entries') + ' will be ignored.' : '';
  const message = 'Apply ' + file.name + '?\n\n'
    + (changing.length ? plural(changing.length, 'setting') + ' will change.' + ignored + ' Your API keys stay as they are.' : 'Your settings already match.' + ignored)
    + (named.length ? '\n\nSwitches that change:\n' + bullets(named) : '')
    + (adding.length || levelChange ? '\n\nAdded to your lists:\n' + bullets(adding.concat(levelChange ? [levelChange] : [])) + '\nNothing you already have is removed.' : '')
    + (plan && plan.filterLists.length ? '\n\nSubscribed lists are fetched again from their addresses.' : '');
  if (!confirm(message)) { setResult('backup', 'Import cancelled. Nothing was changed.', ''); return; }
  const done = [];
  try {
    if (changing.length) {
      const patch = {};
      changing.forEach((key) => { patch[key] = result.settings[key]; });
      await writeConfig(patch);
      done.push(plural(changing.length, 'setting'));
    }
  } catch (error) {
    setResult('backup', 'Could not apply the settings, so nothing was changed: ' + error.message, 'err');
    return;
  }
  let outcome = { failed: [], notes: [] };
  if (plan) {
    setResult('backup', 'Adding to your lists…', '');
    outcome = await applyListsPlan(plan, have);
    const a = outcome.added;
    done.push(...[[a.blockedSites, 'blocked site'], [a.trustedScriptSites, 'trusted script site'], [a.trustedDownloadSites, 'trusted download site'], [a.firewall, 'firewall decision'],
      [a.hidden, 'hidden element'], [a.filterLines, 'filter rule'], [a.filterLists, 'subscribed list']].filter(([n]) => n).map(([n, word]) => plural(n, word)));
    void loadListsBundle();
    void loadRules();
    void loadSubscriptions();
    void loadSites();
  }
  paint();
  const failed = outcome.failed;
  setResult('backup', (done.length ? 'From ' + file.name + ': applied ' + done.join(', ') + '.' : 'Nothing from ' + file.name + ' could be applied.')
    + (result.ignored ? ' Ignored ' + result.ignored + ' unrecognised.' : '')
    + (failed.length ? ' ' + plural(failed.length, 'entry', 'entries') + ' couldn’t be added: ' + failed.slice(0, 3).join('; ') + (failed.length > 3 ? '; …' : '') + '.' : '')
    + (outcome.notes.length ? ' ' + outcome.notes.join(' ') : '')
    + (held ? ' Clearing browser history stays off until you allow history access.' : ''), failed.length ? 'warn' : 'ok');
}

