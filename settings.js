const POPUP_DEFAULTS = DATA.popupDefaults;
const IMPORT_ONLY_DEFAULTS = DATA.importOnlyDefaults;
const IMPORT_SCHEMA = Object.assign({}, IMPORT_ONLY_DEFAULTS, POPUP_DEFAULTS);
const SETTINGS_FILE_MARKER = 'wardenone-settings';
