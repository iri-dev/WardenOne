/* The rules the popup applies on every save: a provider without a key is off, the fingerprint
   alias folds into its switch, and leaving Silent mode puts back a silence nobody chose. */
function tidyConfig(next, before, patch) {
  Object.keys(KEYED).forEach((key) => { if (!String(next[KEYED[key]] || '').trim()) next[key] = false; });
  if ('antiFingerprintNoise' in patch) next.antiFingerprint = false;
  if (before.silentMode === true && next.silentMode !== true && next.showToasts === false && next.showBadge === false) {
    next.showToasts = true;
    next.showBadge = true;
  }
}
let writeChain = Promise.resolve();
/* Read-modify-write, one at a time. The stored config is read again at the moment of writing and
   only the keys changed here are laid on top, so a change the popup made a second ago survives;
   the read and the write hold the config lock (config-lock.js), so one made at the same moment
   does too. A private window's pages and worker have their own lock; if one of them wrote over
   this change without seeing it, the same patch is applied again (confirmConfigWrite). */
function writeConfig(patch, triesLeft, operationOrder) {
  let id = '';
  let order = operationOrder;
  let changedKeys = [];
  const run = writeChain.then(() => withConfigLock(async () => {
    const stored = await localRead([CONFIG_KEY, WO_CONFIG_WRITES_KEY]);
    const before = isObj(stored[CONFIG_KEY]) ? stored[CONFIG_KEY] : {};
    /* A function patch is worked out from what is stored now, for maps another page may be editing. */
    const delta = typeof patch === 'function' ? patch(before) : patch;
    changedKeys = Object.keys(delta);
    const next = Object.assign({}, before, delta);
    tidyConfig(next, before, delta);
    const stamp = stampConfigWrite(stored[WO_CONFIG_WRITES_KEY], changedKeys, order);
    id = stamp.id;
    order = stamp.order;
    await localWrite({ [CONFIG_KEY]: next, [WO_CONFIG_WRITES_KEY]: stamp.record });
    return next;
  })).then((next) => {
    adoptConfig(next);
    confirmConfigWrite(id, (left) => { writeConfig(patch, left, order).catch(() => {}); }, triesLeft, changedKeys, order);
    return next;
  });
  writeChain = run.catch(() => {});
  return run;
}
/* Ask the worker, and hand back its answer instead of throwing, so each caller words its own failure. */
const ask = (message) => new Promise((resolve) => {
  try {
    chrome.runtime.sendMessage(message, (reply) => {
      const error = chrome.runtime.lastError;
      resolve(error ? { ok: false, error: error.message } : (reply || { ok: false, error: 'WardenOne did not answer.' }));
    });
  } catch (error) { resolve({ ok: false, error: String(error && error.message || error) }); }
});

